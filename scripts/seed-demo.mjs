function build() {
  /* DEMO_PEPPER lets the test suite seed against its own throwaway pepper. */
  const pepper = process.env.DEMO_PEPPER || readPepper();
  const now = Date.now();
  const out = ['-- LOCAL DEMO ACCOUNTS — generated by scripts/seed-demo.mjs. Never apply to production.'];
  for (const s of DEMO.staff) {
    out.push(`INSERT OR REPLACE INTO staff_users (id,email,username,pass_hash,role,name,initials,active,must_change,created_at) VALUES (${q(s.id)},${q(s.email)},${q(s.user)},${q(pack(s.pass))},${q(s.role)},${q(s.name)},'הד',1,0,${now});`);
    for (const l of s.levels || []) out.push(`INSERT OR IGNORE INTO teacher_levels (teacher_id, level_id) VALUES (${q(s.id)},${q(l)});`);
  }
  for (const s of DEMO.students) {
    const norm = s.code.replace(/-/g, '');
    const hash = createHash('sha256').update(pepper + '$' + norm).digest('hex');
    out.push(`INSERT OR REPLACE INTO staff_users (id,email,username,pass_hash,role,name,initials,active,must_change,created_at) VALUES (${q(s.id)},${q(s.id + '@students.invalid')},NULL,'!',${q('תלמיד')},${q(s.name)},'הד',1,0,${now});`);
    out.push(`DELETE FROM student_codes WHERE user_id=${q(s.id)};`);
    out.push(`INSERT INTO student_codes (code_hash,user_id,issued_by,created_at) VALUES (${q(hash)},${q(s.id)},'demo-admin',${now});`);
    for (const l of s.levels) {
      out.push(`INSERT OR IGNORE INTO enrollments (id,user_id,level_id,status,started_at,created_by) VALUES (${q('en-' + s.id + '-' + l)},${q(s.id)},${q(l)},'active',${now},'demo-admin');`);
    }
  }
  mkdirSync(join(ROOT, 'seed'), { recursive: true });
  writeFileSync(process.env.DEMO_SQL_OUT || join(ROOT, 'seed', 'demo.sql'), out.join('\n') + '\n');
  console.log('seed/demo.sql written (LOCAL DEMO ONLY).');
  console.log('\nDemo sign-in (local only):');
  for (const s of DEMO.staff) console.log(`  staff   ${s.user.padEnd(14)} ${s.pass.padEnd(20)} ${s.role}`);
  for (const s of DEMO.students) console.log(`  student code ${s.code}   ${s.levels.join(', ')}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) build();
