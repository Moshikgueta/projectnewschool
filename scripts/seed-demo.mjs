#!/usr/bin/env node
/* LOCAL DEMONSTRATION ACCOUNTS — never run against the production database.

     node scripts/seed-demo.mjs            # writes seed/demo.sql (+ .dev.vars if missing)
     npm run demo                          # schema + content + demo accounts + wrangler dev

   Creates clearly labelled demo accounts in the LOCAL D1 so the platform can
   be tried end to end. Passwords and codes below are public on purpose: they
   only work against a local database seeded by this script, with the local
   pepper this script writes to .dev.vars. The script refuses to write SQL
   that targets anything else — it only produces a file; `npm run demo`
   applies it with --local. */

import { writeFileSync, existsSync, readFileSync, mkdirSync } from 'node:fs';
import { pbkdf2Sync, randomBytes, createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEV_VARS = join(ROOT, '.dev.vars');
const DEFAULT_PEPPER = 'local-demo-pepper-not-for-production';

function readPepper() {
  if (!existsSync(DEV_VARS)) {
    writeFileSync(DEV_VARS,
      `# Local development only — generated by scripts/seed-demo.mjs\n` +
      `STUDENT_CODE_PEPPER=${DEFAULT_PEPPER}\nDEMO_MODE=1\n`);
    return DEFAULT_PEPPER;
  }
  const m = readFileSync(DEV_VARS, 'utf8').match(/^STUDENT_CODE_PEPPER=(.*)$/m);
  if (!m) throw new Error('.dev.vars exists but has no STUDENT_CODE_PEPPER — add one and re-run.');
  return m[1].trim();
}

const q = v => v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v)
  : "'" + String(v).replace(/'/g, "''") + "'";

function pack(pass) {
  const salt = randomBytes(16);
  const hash = pbkdf2Sync(pass, salt, 100000, 32, 'sha256');
  return `pbkdf2$100000$${salt.toString('hex')}$${hash.toString('hex')}`;
}

