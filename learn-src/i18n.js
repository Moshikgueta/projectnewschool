export function pct(x) {
  return x === null || x === undefined ? '—' : Math.round(x * 100) + '%';
}

export function dateHe(ts) {
  if (!ts) return '';
  return new Date(ts).toLocaleDateString('he-IL', { day: 'numeric', month: 'short' });
}
